/**
 * 2D side view generated by walking the component tree. Symmetric top-level
 * components (nose/transition/body) form the axial chain; children draw on
 * or inside their parent at their resolved axial position and can be DRAGGED
 * axially (snapping to structural anchors — tube ends, sibling edges).
 * Clustered inner tubes draw one outline per cluster position.
 * CG/CP markers use standard rocketry symbols.
 */

interface Ctx {
  scale: number;
  cy: number;
  x0: number;
}

const num = (n: ComponentNode, key: string, fb: number): number =>
  typeof n[key] === 'number' ? (n[key] as number) : fb;

const fillOf = (n: ComponentNode, dflt: string): string =>
  typeof n['color'] === 'string' ? (n['color'] as string) : dflt;

/** Client px a press may wander before it counts as a pan rather than a click.
 *  Matches the drag threshold in onMove — a physical click jitters 1-3 px. */
const PAN_SLOP = 4;

const MARKER_R = 9;

/**
 * Ruler gutter thickness (viewBox px). The desktop uses one 20 px band for
 * both (ScaleScrollPane.RULER_SIZE); the left band is wider here because its
 * labels are drawn INSIDE it horizontally — the same thing the desktop does,
 * but its numbers are radii (small, few digits) and ours may be a diameter in
 * millimetres.
 */
export const RULER_TOP = 18;
export const RULER_LEFT = 30;

/** Total viewBox px of height reserved for the two callout lanes (S2). */
export const CALLOUT_LANES = 34;
/** Lane-center distance from the airframe edge (or marker edge, if wider). */
const LANE_GAP = 13;
/** CP label footprint in the lower lane, relative to cpX: dot (r 4) plus
 *  the "CP" text to its right — the margin text must not land on it. */
const CP_LABEL_L = 6;
const CP_LABEL_R = 27;
/** Rough half-width of the margin text (13 px bold ≈ 7.2 px per char). */
const marginHalfW = (text: string) => (text.length * 7.2) / 2;

/** Same tiered glyphs/vocabulary as StatTiles / SimResults. */
const STABILITY_GLYPH: Record<StabilityState, string> = { under: '⚠', over: '△', ok: '✓' };
const STABILITY_WORD: Record<StabilityState, string> = { under: 'under-stable', over: 'over-stable', ok: 'ok' };
const STABILITY_VAR: Record<StabilityState, string> = {
  under: 'var(--status-serious)', over: 'var(--status-warn)', ok: 'var(--status-good)',
};

export interface CalloutLayout {
  cg: { x: number; leaderY1: number; leaderY2: number } | null;
  cp: { x: number; leaderY1: number; leaderY2: number } | null;
  margin: { x: number; y: number } | null;
}

/**
 * Leader-line callout geometry (S2): dashed leaders run from the centerline
 * markers to labeled dots in clear lanes above (CG) and below (CP) the drawn
 * airframe; the margin text sits in the LOWER lane midway between the two —
 * the upper-right corner belongs to the export/zoom control strip, which the
 * text collided with the moment the canvas became the hero (batch 08-21c) —
 * clamped inside the viewBox and nudged off the CP label when they'd collide
 * (leftward as the fallback when the right side has no room).
 *
 * @param halfPx drawn vertical half-extent (viewBox px) = vHalf * scale
 * @param top    first usable y — the horizontal ruler's gutter, 0 without one
 * @param left   first usable x — the vertical ruler's gutter, 0 without one
 */
export function calloutLayout(
  cgX: number | null, cpX: number | null,
  cy: number, halfPx: number, w: number, h: number,
  marginText: string | null, top = 0, left = 0,
): CalloutLayout {
  const laneTop = Math.max(top + 10, cy - Math.max(halfPx, MARKER_R) - LANE_GAP);
  const laneBottom = Math.min(h - 10, cy + Math.max(halfPx, MARKER_R) + LANE_GAP);
  const cg = cgX === null ? null : { x: cgX, leaderY1: cy - MARKER_R, leaderY2: laneTop };
  const cp = cpX === null ? null : { x: cpX, leaderY1: cy + MARKER_R, leaderY2: laneBottom };
  let margin: { x: number; y: number } | null = null;
  if (marginText !== null && cgX !== null && cpX !== null) {
    const halfW = marginHalfW(marginText);
    const clamp = (x: number) => Math.min(w - halfW - 2, Math.max(left + halfW + 2, x));
    const collides = (x: number) => x + halfW > cpX - CP_LABEL_L && x - halfW < cpX + CP_LABEL_R;
    let x = clamp((cgX + cpX) / 2);
    if (collides(x)) {
      const right = clamp(cpX + CP_LABEL_R + halfW);
      x = collides(right) ? clamp(cpX - CP_LABEL_L - halfW) : right;
    }
    margin = { x, y: laneBottom };
  }
  return { cg, cp, margin };
}

/** Tab front edge from the fin's leading edge (AxialMethod.getAsPosition). */
export function finTabFront(n: ComponentNode, finLen: number): number {
  const offset = num(n, 'tabOffset', 0);
  const tabLen = num(n, 'tabLength', 0);
  const method = typeof n['tabOffsetMethod'] === 'string' ? (n['tabOffsetMethod'] as string) : 'middle';
  if (method === 'top') return offset;
  if (method === 'bottom') return offset + (finLen - tabLen);
  return offset + (finLen - tabLen) / 2;
}

function axialStart(child: ComponentNode, childLen: number, pStart: number, pLen: number): number {
  const pos = (child.position ?? { method: 'top', offset: 0 }) as ComponentPosition;
  return pStart + startFromPosition(pos, childLen, pLen);
}

interface DragState {
  childId: string;
  parent: ComponentNode;
  child: ComponentNode;
  pLen: number;
  /** parent-relative start at pointer-down (m) */
  relStart: number;
  pointerX: number;
  /** viewBox px per client px */
  clientScale: number;
}

export function TreeSchematic({ tree, info, motors, onPatchNode, maxHeight = 480, selectedId, onSelect, exportData, onError, vertical, fillHeight, onNaturalHeight, roll: rollProp, onRoll }: {
  tree: RocketTree;
  info: StaticInfo | null;
  /** Loaded motor case dimensions (m) keyed by mount node id — drawn to
   *  scale; `label` is the designation printed in the case when it fits (S5). */
  motors?: Record<string, { length: number; diameter: number; label?: string }>;
  onPatchNode?: (id: string, patch: Partial<ComponentNode>) => void;
  /** Cap on the drawing's on-screen height (px). */
  maxHeight?: number;
  /** Two-way selection sync with the component tree (2026-08-05b #21). */
  selectedId?: string | null;
  onSelect?: (id: string) => void;
  /** When set, ⬇ SVG / ⬇ PNG export buttons appear (issue 2026-08-11a). */
  exportData?: Omit<ExportData, 'spanM'>;
  /**
   * Reports an export failure to the caller's note channel. Rasterising really
   * can fail — svgToImage rejects from img.onerror, and a big rocket at 7680px
   * can exhaust the canvas — and the awaited rejection used to go nowhere: the
   * button just did nothing, which reads as "the export is broken" with
   * nothing to report.
   */
  onError?: (message: string) => void;
  /** Nose-up view (S1 rotate / S4 phone): the horizontal layout rotates as
   *  one group to fit the container's HEIGHT. Read-mostly — drag, pan, zoom
   *  and the export/zoom controls are off; hover and click-select stay. */
  vertical?: boolean;
  /** Hero canvas (batch 08-21e): the drawing surface spans the container's
   *  FULL height instead of the adaptive content height — otherwise the svg's
   *  invisible clip edges sit mid-canvas and a zoomed rocket "slides under"
   *  what reads as a black box. Ignored in vertical mode (which fills by its
   *  own rule); overrides maxHeight. */
  fillHeight?: boolean;
  /**
   * v0.076 fit-to-content: reports the drawing's NATURAL height (px) — the
   * rocket's cross extent at width-fit scale plus padding and callout lanes,
   * uncapped — so the hero stage can size to the rocket instead of the
   * window. Only fires in fillHeight horizontal mode. Depends on container
   * WIDTH and geometry, never on container height or zoom, so it cannot
   * feed the measure→draw→grow loop the styles.css note warns about.
   */
  onNaturalHeight?: (px: number) => void;
  /**
   * Roll about the rocket's long axis (rad), the desktop's rotation slider.
   * Optional and CONTROLLED-OR-NOT: pass both to share one angle with the Aft
   * view (App does), pass neither and the view keeps its own. Zero = the
   * design's own clock angles, so an uncontrolled instance draws exactly what
   * it drew before the slider existed.
   */
  roll?: number;
  onRoll?: (rad: number) => void;
}) {
  const { prefs, setPrefs } = usePrefs();
  const svgRef = useRef<SVGSVGElement>(null);
  const wrapRef = useRef<HTMLDivElement>(null);
  const drag = useRef<DragState | null>(null);
  // True once the current gesture moved far enough to be a drag — a click
  // that follows a real drag must not change the selection.
  const dragMoved = useRef(false);
  // Container width (CSS px). The viewBox adopts it 1:1, so the drawing fills
  // the column at native pixel scale on any monitor instead of a fixed 640px
  // canvas stretched to fit.
  const [cw, setCw] = useState(640);
  // Container height (CSS px) — the length axis in vertical mode. Stays at
  // the fallback when the wrap has no definite height to inherit.
  const [chPx, setChPx] = useState(480);
  // Hovered component (S5): accent wash + name tag drawn topmost. Enter/
  // leave never fire from touch, so phones skip hover naturally.
  const [hoverId, setHoverId] = useState<string | null>(null);
  // View transform (zoom & pan) in viewBox px; identity = whole rocket fits.
  const [zoom, setZoom] = useState({ k: 1, x: 0, y: 0 });
  // Roll, when the caller doesn't own it. See the `roll` prop.
  const [rollLocal, setRollLocal] = useState(0);
  const roll = rollProp ?? rollLocal;
  const setRoll = onRoll ?? setRollLocal;
  // `active` only becomes true once the pointer has travelled past PAN_SLOP —
  // see beginPan for why a press must not pan until then.
  const pan = useRef<
    { pointerX: number; pointerY: number; x0: number; y0: number; active: boolean } | null
  >(null);

  // --- measure the axial chain ---
  // Stages flatten into one nose-to-tail chain (sustainer first, boosters
  // after — the desktop's stacking order); legacy flat trees pass through.
  const chain = tree.components.flatMap((n) => (n.type === 'stage' ? n.children ?? [] : [n]));
  let totalLen = 0;
  let maxR = 0.001;
  for (const n of chain) {
    if (n.type === 'nosecone' || n.type === 'bodytube' || n.type === 'transition') {
      totalLen += num(n, 'length', 0);
      maxR = Math.max(maxR, num(n, 'aftRadius', 0), num(n, 'outerRadius', 0), num(n, 'foreRadius', 0));
    }
  }
  // A fin set's vertical span: freeform fins carry no 'height' key — their
  // reach is the outline's y-max (the 0.03 default clipped tall freeform fins
  // out of the adaptive-height frame).
  const finSpan = (n: ComponentNode): number => {
    if (!n.type.endsWith('finset')) return 0;
    if (n.type === 'freeformfinset') {
      const pts = n['points'];
      if (Array.isArray(pts) && pts.length > 0) {
        return Math.max(0, ...pts.map((p) => (Array.isArray(p) ? Number(p[1]) || 0 : 0)));
      }
    }
    // Tube fins reach one tube diameter above the body surface.
    if (n.type === 'tubefinset') return 2 * tubeFinRadius(n, maxR);
    return num(n, 'height', 0.03);
  };
  const protuberanceSpan = (n: ComponentNode): number =>
    (n.type === 'fairing' ? num(n, 'height', 0.02)
      : (n.type as string) === 'protuberance' ? num(n, 'height', 0.01)
        : 0);
  const finH = Math.max(
    0,
    ...collect(tree.components, finSpan),
    ...collect(tree.components, protuberanceSpan),
  );
  totalLen = Math.max(totalLen, 0.05);

  // Vertical half-extent (m): the core body + fins, plus any off-axis pod's
  // reach (its centerline radius + its own body + its fins) so pods don't clip.
  let vHalf = maxR + finH;
  const scanRadial = (nodes: ComponentNode[], parentR: number) => {
    for (const n of nodes) {
      if (isAssembly(n.type)) {
        const podFin = Math.max(0, ...collect(n.children ?? [], finSpan));
        vHalf = Math.max(vHalf, resolveAssemblyRadius(n, parentR) + assemblyBoundingRadius(n) + podFin);
        scanRadial(n.children ?? [], assemblyBoundingRadius(n));
      } else {
        const r = Math.max(num(n, 'aftRadius', 0), num(n, 'outerRadius', 0), num(n, 'foreRadius', 0)) || parentR;
        scanRadial(n.children ?? [], r);
      }
    }
  };
  scanRadial(chain, maxR);

  // Vertical mode swaps the container roles BEFORE layout: all layout math
  // stays horizontal (length along x) and the finished drawing rotates
  // nose-up as one group, so the length axis fits the container HEIGHT and
  // the cross extent its width.
  const w = Math.max(320, vertical ? chPx : cw);
  const pad = 26;
  /**
   * Dimensional rulers (@atestani, 26 Aug: "Scales as in OpenRocket like the
   * top and left side"). Off in ⟳90° mode: that drawing is one rigid rotation
   * of this layout, so a ruler would come out running down the right-hand
   * side with sideways numbers. Absent preference = ON, like the desktop,
   * where the rulers are not optional at all.
   */
  const rulersPref = prefs.rulers2d ?? true;
  const rulers = !vertical && rulersPref;
  // The roll slider's column, and the ruler gutters. All three are surrendered
  // by the DRAWING, so every fit below works from the inset box — and every
  // pointer↔model conversion is unaffected, because they move the origin
  // without touching `scale`.
  const rollW = vertical ? 0 : ROLL_COL;
  const gutX = rollW + (rulers ? RULER_LEFT : 0);
  const gutY = rulers ? RULER_TOP : 0;
  // Height follows the rocket's own proportions (clamped): a long thin
  // rocket gets a wide low band, not a fixed frame of empty sky. When info
  // is present the CG/CP callout lanes need sky of their own, so their
  // allowance is added to the height AND kept out of the vertical fit —
  // otherwise a height-limited short/fat rocket would fill it and clip them.
  const lanes = info ? CALLOUT_LANES : 0;
  const crossCap = vertical ? Math.max(160, cw) : maxHeight;
  // The adaptive content height, uncapped — what the drawing would take if
  // nothing constrained it. The fillHeight branch still fills its container;
  // this is what the container itself sizes FROM (via onNaturalHeight).
  const naturalRaw = Math.round(Math.max(
    200, 2 * vHalf * ((w - 2 * pad - gutX) / totalLen) + 2 * pad + lanes + gutY,
  ));
  // Reported quantized to 8px: naturalRaw moves with every 1px of container
  // width, and each NEW reported value re-renders the whole App — a window
  // drag-resize would cascade an app-wide render per tick (review finding,
  // v0.076). Quantized, most ticks report the same value and React bails.
  const naturalH = Math.round(naturalRaw / 8) * 8;
  const h = vertical || !fillHeight
    ? Math.round(Math.min(crossCap, Math.max(200, naturalRaw)))
    : Math.max(200, chPx);
  const scale = Math.max(1e-6, Math.min(
    (w - 2 * pad - gutX) / totalLen,
    (h - 2 * pad - lanes - gutY) / (2 * vHalf),
  ));
  const ctx: Ctx = { scale, cy: gutY + (h - gutY) / 2, x0: pad + gutX };

  // Report the natural height to the hero stage (fit-to-content, v0.076).
  // Callback identity rides a ref so a new inline closure per parent render
  // doesn't re-fire the effect; the effect keys on the VALUE.
  const onNaturalHeightRef = useRef(onNaturalHeight);
  onNaturalHeightRef.current = onNaturalHeight;
  useEffect(() => {
    if (vertical || !fillHeight) return;
    onNaturalHeightRef.current?.(naturalH);
  }, [naturalH, vertical, fillHeight]);

  const beginDrag = (child: ComponentNode, parent: ComponentNode, pLen: number) =>
    (e: React.PointerEvent) => {
      if (!onPatchNode || !child.id) return;
      const rect = svgRef.current?.getBoundingClientRect();
      if (!rect || rect.width === 0) return;
      e.stopPropagation(); // don't also start a background pan
      dragMoved.current = false;
      const pos = (child.position ?? { method: 'top', offset: 0 }) as ComponentPosition;
      drag.current = {
        childId: child.id,
        parent,
        child,
        pLen,
        relStart: startFromPosition(pos, axialLength(child), pLen),
        pointerX: e.clientX,
        clientScale: w / rect.width,
      };
      (e.currentTarget as Element).setPointerCapture?.(e.pointerId);
    };

  /**
   * Clears the "this press became a drag" latch at the START of every press.
   * Attached in the CAPTURE phase on the svg so it runs whatever was pressed,
   * and in vertical mode too. It used to be cleared only inside beginDrag,
   * which is attached to draggable CHILDREN alone — so once any drag passed
   * the 4 px threshold the flag stayed set, and the axial chain (nose cone,
   * body tube, transition) has no pointerdown handler of its own to clear it.
   * Clicking those became a permanent no-op while children kept working.
   */
  const resetDragLatch = () => { dragMoved.current = false; };

  /**
   * Arms a background pan — but does NOT start one, and deliberately does not
   * capture the pointer yet.
   *
   * This handler runs for every press that reaches the svg, which is every
   * press on the axial chain (nose cone, body tube, transition): only
   * draggable CHILDREN stopPropagation in beginDrag. It used to pan on the
   * very first pointermove and capture the pointer immediately, so the 1-3 px
   * of jitter in an ordinary physical click dragged the whole drawing out from
   * under the pointer between press and release. The click then landed on the
   * <svg> instead of the shape and selecting those parts did nothing at all —
   * while children stayed fine, and the vertical view (which attaches neither
   * handler) worked perfectly. Capturing on press made it worse by retargeting
   * the release as well.
   *
   * Both now wait for real movement, so a click stays a click.
   */
  const beginPan = (e: React.PointerEvent) => {
    const rect = svgRef.current?.getBoundingClientRect();
    if (!rect || rect.width === 0) return;
    pan.current = { pointerX: e.clientX, pointerY: e.clientY, x0: zoom.x, y0: zoom.y, active: false };
  };

  const onMove = (e: React.PointerEvent) => {
    const d = drag.current;
    if (d && onPatchNode) {
      if (Math.abs(e.clientX - d.pointerX) > 4) dragMoved.current = true;
      const dxModel = ((e.clientX - d.pointerX) * d.clientScale) / (scale * zoom.k);
      const anchors = anchorStarts(d.parent, d.child);
      const epsilon = (6 * 1) / (scale * zoom.k); // ~6 screen px of magnetism
      const snapped = snapStart(d.relStart + dxModel, anchors, epsilon);
      const pos = (d.child.position ?? { method: 'top', offset: 0 }) as ComponentPosition;
      onPatchNode(d.childId, {
        position: {
          method: pos.method,
          offset: offsetForStart(pos.method, snapped, axialLength(d.child), d.pLen),
        },
      });
      return;
    }
    const p = pan.current;
    if (p) {
      const dx = e.clientX - p.pointerX;
      const dy = e.clientY - p.pointerY;
      // Below the slop this press is still a click, not a pan. Once it IS a
      // pan, take the pointer so the gesture survives leaving the svg.
      if (!p.active) {
        if (Math.abs(dx) < PAN_SLOP && Math.abs(dy) < PAN_SLOP) return;
        p.active = true;
        (e.currentTarget as Element).setPointerCapture?.(e.pointerId);
      }
      const rect = svgRef.current?.getBoundingClientRect();
      if (!rect || rect.width === 0) return;
      const clientScale = w / rect.width;
      setZoom((z) => ({ ...z, x: p.x0 + dx * clientScale, y: p.y0 + dy * clientScale }));
    }
  };

  const endDrag = () => { drag.current = null; pan.current = null; };

  // Track the container's size so the viewBox can follow it (height feeds
  // the vertical mode's length axis).
  useEffect(() => {
    const el = wrapRef.current;
    if (!el) return;
    const obs = new ResizeObserver(() => {
      if (el.clientWidth > 0) setCw(el.clientWidth);
      if (el.clientHeight > 0) setChPx(el.clientHeight);
    });
    obs.observe(el);
    return () => obs.disconnect();
  }, []);

  // Wheel zoom around the pointer. Native listener: React's onWheel is
  // passive, so preventDefault (to stop page scroll) must be attached here.
  useEffect(() => {
    const svg = svgRef.current;
    if (!svg || vertical) return;
    const onWheel = (e: WheelEvent) => {
      e.preventDefault();
      const rect = svg.getBoundingClientRect();
      if (rect.width === 0) return;
      const px = ((e.clientX - rect.left) / rect.width) * w;
      const py = ((e.clientY - rect.top) / rect.height) * h;
      setZoom((z) => {
        const k = Math.min(12, Math.max(1, z.k * (e.deltaY < 0 ? 1.2 : 1 / 1.2)));
        if (k === z.k) return z;
        // Keep the model point under the cursor fixed while scaling.
        const mx = (px - z.x) / z.k;
        const my = (py - z.y) / z.k;
        const next = { k, x: px - mx * k, y: py - my * k };
        return k === 1 ? { k: 1, x: 0, y: 0 } : next;
      });
    };
    svg.addEventListener('wheel', onWheel, { passive: false });
    return () => svg.removeEventListener('wheel', onWheel);
  }, [w, h, vertical]);

  // Button zoom steps around the view center (the wheel handles precise
  // pointer-anchored zoom; these make the capability visible).
  const zoomBy = (f: number) => setZoom((z) => {
    const k = Math.min(12, Math.max(1, z.k * f));
    if (k === z.k) return z;
    const mx = (w / 2 - z.x) / z.k;
    const my = (h / 2 - z.y) / z.k;
    return k === 1 ? { k: 1, x: 0, y: 0 } : { k, x: w / 2 - mx * k, y: h / 2 - my * k };
  });

  // Selection sync: click any drawn component to select it in the tree; the
  // selected component draws with an accent outline.
  const isSel = (n: ComponentNode) => !!selectedId && n.id === selectedId;
  const clickable = (n: ComponentNode) => ({
    ...(n.id
      ? {
        onPointerEnter: () => setHoverId(n.id!),
        onPointerLeave: () => setHoverId((cur) => (cur === n.id ? null : cur)),
      }
      : {}),
    ...(onSelect && n.id
      ? {
        onClick: (e: React.MouseEvent) => {
          e.stopPropagation();
          if (!dragMoved.current) onSelect(n.id!);
        },
        style: { cursor: 'pointer' } as React.CSSProperties,
      }
      : {}),
  });
  const selStroke = (n: ComponentNode, dflt: string) => (isSel(n) ? 'var(--accent)' : dflt);
  const selWidth = (n: ComponentNode, dflt: number | string = 1) => (isSel(n) ? 2 : dflt);

  // Nose-up rendering rotates the whole drawing; every text label counter-
  // rotates about its own anchor so it still reads horizontally.
  const textUp = (x: number, y: number) =>
    (vertical ? { transform: `rotate(-90 ${x} ${y})` } : {});

  // --- render chain + children ---
  const shapes: React.ReactNode[] = [];
  // Dashed "shadow" shapes (inner components, shoulders) paint AFTER the whole
  // hull: SVG stacks by document order, so a coupler overhanging into the NEXT
  // tube used to vanish under that tube's opaque fill (while the overhang into
  // the PREVIOUS tube, already painted, stayed visible — the owner's ebay report).
  const overlay: React.ReactNode[] = [];
  let key = 0;

  // Hovered component's drawn extent (layout px), unioned across instances
  // (cluster copies, pod rings) as the shapes render.
  const hoverBoxes: { x0: number; y0: number; x1: number; y1: number }[] = [];
  let hoverName = '';
  const noteHover = (n: ComponentNode, x0: number, y0: number, x1: number, y1: number) => {
    if (!hoverId || n.id !== hoverId) return;
    hoverName = n.name ?? DISPLAY_NAME[n.type];
    hoverBoxes.push({
      x0: Math.min(x0, x1), y0: Math.min(y0, y1),
      x1: Math.max(x0, x1), y1: Math.max(y0, y1),
    });
  };

  // Loaded motor case (S5): launch-orange tint at the real case size, with
  // the designation printed in the case when it's long enough to carry it.
  const motorShapes = (
    motor: { length: number; diameter: number; label?: string },
    mStart: number, cY: number,
  ): React.ReactNode[] => {
    const mR = motor.diameter / 2;
    const out: React.ReactNode[] = [
      <rect key={key++} x={ctx.x0 + mStart * ctx.scale} y={cY - mR * ctx.scale}
        width={Math.max(2, motor.length * ctx.scale)} height={Math.max(2, 2 * mR * ctx.scale)}
        rx="1" fill="var(--launch)" fillOpacity="0.85"
        stroke="#e0764a" strokeWidth="0.8"
        style={{ pointerEvents: 'none' }} />,
    ];
    if (motor.label && motor.length * ctx.scale > 36) {
      const lx = ctx.x0 + (mStart + motor.length / 2) * ctx.scale;
      out.push(
        <text key={key++} x={lx} y={cY} textAnchor="middle" dominantBaseline="central"
          fontSize="10" fontWeight="bold" fill="#ffffff" {...textUp(lx, cY)}
          style={{ pointerEvents: 'none' }}>
          {motor.label}
        </text>,
      );
    }
    return out;
  };

  /**
   * Where each fin of a set lands in the side view, as a signed foreshortening
   * factor on its radial coordinates: +1 straight up, 0 edge on, −1 straight
   * down. This is exactly what the desktop draws — `FinSetShapes.getShapesSide`
   * transforms the fin's own points by `rotate_x(clock angle)` and plots
   * (x, y), so a point at radius r lands at `r·cos θ`
   * (FinSetShapes.java:41-60 + RocketFigure.axialRotation, 24.12).
   *
   * Instances whose whole silhouette falls inside the body outline are
   * dropped. The desktop draws them anyway — outlines only, so its worst case
   * is a faint line — but our fins are filled, and an edge-on one collapses to
   * a bar lying along the centreline of the airframe.
   *
   * @param reach the fin's outer radius (body radius + span)
   */
  const finFactors = (n: ComponentNode, pRadius: number, reach: number, dfltCount = 3): number[] => {
    const count = Math.max(1, Math.round(num(n, 'finCount', dfltCount)));
    const base = num(n, 'rotation', 0) + roll;
    const out: number[] = [];
    for (let i = 0; i < count; i++) {
      const p = Math.cos(base + (2 * Math.PI * i) / count);
      if (reach * Math.abs(p) > pRadius) out.push(p);
    }
    // Furthest-out last. Same-colored fins overlap once a set is rolled off
    // its symmetry, and the one that reaches past the others reads best on
    // top. (The desktop needs no such rule — it draws outlines, not fills.)
    return out.sort((a, b) => Math.abs(a) - Math.abs(b));
  };

  const renderChildren = (parent: ComponentNode, pStart: number, pLen: number, pRadius: number, baseY: number) => {
    for (const child of parent.children ?? []) {
      const t = child.type;
      // Off-axis assembly: draw its whole chain once per ring instance at the
      // instance's projected baseline (side view projects y, ignores depth z).
      if (isAssembly(t)) {
        const podChain = child.children ?? [];
        const podLen = assemblyChainLength(child);
        const podRadius = resolveAssemblyRadius(child, pRadius);
        const podStart = axialStart(child, podLen, pStart, pLen);
        const count = Math.max(1, Math.round(num(child, 'instanceCount', 2)));
        for (const off of ringInstanceOffsets(count, podRadius, num(child, 'angleOffset', 0) + roll)) {
          // −y: the cross-section frame's +y is UP, and SVG y grows down.
          renderChain(podChain, podStart, baseY - off.y * ctx.scale);
        }
        continue;
      }
      const grab = {
        ...clickable(child),
        ...(onPatchNode && child.id && !vertical
          ? {
            onPointerDown: beginDrag(child, parent, pLen),
            style: { cursor: 'grab' } as React.CSSProperties,
          }
          : {}),
      };
      // Through-the-wall fin tab: dashed rect from the body surface inward,
      // foreshortened with the fin instance it belongs to.
      const renderTab = (finStart: number, finLen: number, p: number) => {
        const tabH = Math.min(num(child, 'tabHeight', 0), pRadius);
        const tabLen = num(child, 'tabLength', 0);
        if (tabH <= 0 || tabLen <= 0) return;
        const front = finStart + finTabFront(child, finLen);
        const yInner = baseY - (pRadius - tabH) * p * ctx.scale;
        const ySurface = baseY - pRadius * p * ctx.scale;
        shapes.push(
          <rect key={key++} x={ctx.x0 + front * ctx.scale} y={Math.min(yInner, ySurface)}
            width={Math.max(2, tabLen * ctx.scale)} height={Math.max(1.5, Math.abs(yInner - ySurface))}
            fill={fillOf(child, '#b9b7b0')} fillOpacity="0.35"
            stroke="#7a786f" strokeWidth="1" strokeDasharray="3 2"
            style={{ pointerEvents: 'none' }} />,
        );
      };
      if (t === 'freeformfinset') {
        const raw = (child['points'] as [number, number][] | undefined) ?? [];
        if (raw.length >= 3) {
          const chord = Math.max(...raw.map((p) => p[0]));
          const start = axialStart(child, chord, pStart, pLen);
          const ymax = Math.max(0, ...raw.map((p) => p[1]));
          noteHover(child, ctx.x0 + start * ctx.scale, baseY - (pRadius + ymax) * ctx.scale,
            ctx.x0 + (start + chord) * ctx.scale, baseY + (pRadius + ymax) * ctx.scale);
          for (const p of finFactors(child, pRadius, pRadius + ymax)) {
            const ptsStr = raw
              .map(([px, py]) => `${ctx.x0 + (start + px) * ctx.scale},${baseY - (pRadius + py) * p * ctx.scale}`)
              .join(' ');
            shapes.push(
              <polygon key={key++} points={ptsStr}
                fill={fillOf(child, '#b9b7b0')} stroke={selStroke(child, '#7a786f')}
                strokeWidth={selWidth(child)} {...grab} />,
            );
            renderTab(start, chord, p);
          }
        }
      } else if (t === 'trapezoidfinset' || t === 'ellipticalfinset') {
        const root = num(child, 'rootChord', 0.05);
        const tip = t === 'trapezoidfinset' ? num(child, 'tipChord', root * 0.6) : 0;
        const sweep = t === 'trapezoidfinset' ? num(child, 'sweep', 0.02) : root / 2;
        const height = num(child, 'height', 0.03);
        const start = axialStart(child, root, pStart, pLen);
        noteHover(child, ctx.x0 + start * ctx.scale, baseY - (pRadius + height) * ctx.scale,
          ctx.x0 + (start + Math.max(root, sweep + tip)) * ctx.scale,
          baseY + (pRadius + height) * ctx.scale);
        for (const p of finFactors(child, pRadius, pRadius + height)) {
          const y0 = baseY - pRadius * p * ctx.scale;
          const yh = baseY - (pRadius + height) * p * ctx.scale;
          const X = ctx.x0 + start * ctx.scale;
          shapes.push(
            t === 'trapezoidfinset' ? (
              <polygon key={key++}
                points={`${X},${y0} ${X + sweep * ctx.scale},${yh} ${X + (sweep + tip) * ctx.scale},${yh} ${X + root * ctx.scale},${y0}`}
                fill={fillOf(child, '#b9b7b0')} stroke={selStroke(child, '#7a786f')}
                strokeWidth={selWidth(child)} {...grab} />
            ) : (
              <path key={key++}
                d={`M ${X} ${y0} Q ${X + (root / 2) * ctx.scale} ${yh - p * 4} ${X + root * ctx.scale} ${y0} Z`}
                fill={fillOf(child, '#b9b7b0')} stroke={selStroke(child, '#7a786f')}
                strokeWidth={selWidth(child)} {...grab} />
            ),
          );
          renderTab(start, root, p);
        }
      } else if (t === 'tubefinset') {
        // Side view: every tube of the ring, at its projected height. A tube
        // runs PARALLEL to the body axis, so unlike a fin it is not squashed
        // by roll — its silhouette stays 2·rt tall and only its centre moves,
        // to (pRadius + rt)·cos θ. Tubes whose silhouette falls entirely
        // inside the airframe are hidden behind it and dropped; that is the
        // honest form of the old "side tubes project onto the body — omitted"
        // shortcut, which drew exactly two tubes whatever the count.
        const len = num(child, 'length', 0.1);
        const rt = tubeFinRadius(child, pRadius);
        const start = axialStart(child, len, pStart, pLen);
        const X = ctx.x0 + start * ctx.scale;
        noteHover(child, X, baseY - (pRadius + 2 * rt) * ctx.scale,
          X + len * ctx.scale, baseY + (pRadius + 2 * rt) * ctx.scale);
        const tubeCount = Math.max(1, Math.round(num(child, 'finCount', 6)));
        const tubeBase = num(child, 'rotation', 0) + roll;
        const tubes: number[] = [];
        for (let i = 0; i < tubeCount; i++) {
          const p = Math.cos(tubeBase + (2 * Math.PI * i) / tubeCount);
          if ((pRadius + rt) * Math.abs(p) + rt > pRadius) tubes.push(p);
        }
        tubes.sort((a, b) => Math.abs(a) - Math.abs(b));
        for (const p of tubes) {
          const yc = baseY - (pRadius + rt) * p * ctx.scale;
          const half = rt * ctx.scale;
          shapes.push(
            <rect key={key++} x={X} y={yc - half}
              width={Math.max(2, len * ctx.scale)} height={2 * half}
              rx="2" fill={fillOf(child, '#c8c5be')} fillOpacity="0.6"
              stroke={selStroke(child, '#7a786f')} strokeWidth={selWidth(child)} {...grab} />,
            <line key={key++} x1={X} y1={yc} x2={X + len * ctx.scale} y2={yc}
              stroke="#7a786f" strokeWidth="0.8" strokeDasharray="4 3"
              style={{ pointerEvents: 'none' }} />,
          );
        }
      } else if (t === 'fairing') {
        // External shroud: SOLID outline (it's on the outside — the owner's spec),
        // drawn on the top surface; radial angle isn't modeled.
        const len = num(child, 'length', 0.08);
        const hgt = num(child, 'height', 0.02);
        const fshape = String(child['fairingShape'] ?? 'halfround');
        const start = axialStart(child, len, pStart, pLen);
        const X = ctx.x0 + start * ctx.scale;
        const y0 = baseY - pRadius * ctx.scale;
        const yh = y0 - hgt * ctx.scale;
        const Xe = X + len * ctx.scale;
        noteHover(child, X, yh, Xe, y0);
        shapes.push(
          fshape === 'streamlined' ? (
            <polygon key={key++}
              points={`${X},${y0} ${X + 0.3 * len * ctx.scale},${yh} ${X + 0.7 * len * ctx.scale},${yh} ${Xe},${y0}`}
              fill={fillOf(child, '#c8c5be')} stroke={selStroke(child, '#7a786f')}
              strokeWidth={selWidth(child)} {...grab} />
          ) : fshape === 'halfround' ? (
            <path key={key++}
              d={`M ${X} ${y0} L ${X} ${yh + 0.35 * (y0 - yh)} Q ${X} ${yh} ${X + Math.min(8, len * ctx.scale * 0.25)} ${yh} L ${Xe - Math.min(8, len * ctx.scale * 0.25)} ${yh} Q ${Xe} ${yh} ${Xe} ${yh + 0.35 * (y0 - yh)} L ${Xe} ${y0} Z`}
              fill={fillOf(child, '#c8c5be')} stroke={selStroke(child, '#7a786f')}
              strokeWidth={selWidth(child)} {...grab} />
          ) : (
            <rect key={key++} x={X} y={yh}
              width={Math.max(2, len * ctx.scale)} height={Math.max(2, hgt * ctx.scale)}
              fill={fillOf(child, '#c8c5be')} stroke={selStroke(child, '#7a786f')}
              strokeWidth={selWidth(child)} {...grab} />
          ),
        );
      } else if ((t as string) === 'protuberance') {
        // A drag bump on the outside: solid outline on the top surface, shaped
        // by its RASAero class — a ramp for an inclined flat plate, a faired
        // nose with a blunt back for "with base drag", faired both ends for
        // "no base drag". Radial angle isn't modeled (same as a launch lug).
        const len = num(child, 'length', 0.06);
        const hgt = num(child, 'height', 0.01);
        const cls = String(child['dragClass'] ?? 'streamlinedbase');
        const start = axialStart(child, len, pStart, pLen);
        const X = ctx.x0 + start * ctx.scale;
        const y0 = baseY - pRadius * ctx.scale;
        const yh = y0 - hgt * ctx.scale;
        const Xe = X + len * ctx.scale;
        noteHover(child, X, yh, Xe, y0);
        const nose = Math.min(0.35 * (Xe - X), Math.max(2, hgt * ctx.scale));
        shapes.push(
          <polygon key={key++}
            points={cls === 'plate'
              ? `${X},${y0} ${Xe},${yh} ${Xe},${y0}`
              : cls === 'streamlined'
                ? `${X},${y0} ${X + nose},${yh} ${Xe - nose},${yh} ${Xe},${y0}`
                : `${X},${y0} ${X + nose},${yh} ${Xe},${yh} ${Xe},${y0}`}
            fill={fillOf(child, '#c8c5be')} stroke={selStroke(child, '#7a786f')}
            strokeWidth={selWidth(child)} {...grab} />,
        );
      } else if (t === 'launchlug' || t === 'railbutton') {
        // Rail buttons are edited via 'outerDiameter' (their only size field)
        // and have no axial 'length' — a button is about as long as it is wide.
        const btnDia = t === 'railbutton' ? num(child, 'outerDiameter', 0.004) : 0;
        const len = t === 'railbutton' ? btnDia : num(child, 'length', 0.01);
        const r = t === 'railbutton' ? btnDia / 2 : num(child, 'outerRadius', 0.002);
        const start = axialStart(child, len, pStart, pLen);
        noteHover(child, ctx.x0 + start * ctx.scale, baseY - (pRadius + 2 * r) * ctx.scale,
          ctx.x0 + (start + len) * ctx.scale, baseY - pRadius * ctx.scale);
        shapes.push(
          <rect key={key++} x={ctx.x0 + start * ctx.scale}
            y={baseY - (pRadius + 2 * r) * ctx.scale}
            width={Math.max(2, len * ctx.scale)} height={Math.max(2, 2 * r * ctx.scale)}
            fill={fillOf(child, '#c8c5be')} stroke={selStroke(child, '#7a786f')}
            strokeWidth={selWidth(child)} {...grab} />,
        );
      } else {
        // Internal component: dashed outline inside the parent. A clustered
        // inner tube draws once per cluster position (side-view projection).
        // Per-type stroke color + a small tag differentiate what used to be
        // identical grey boxes (issue 2026-08-05a #21) — tubes/couplers stay
        // neutral (they really are tube segments), payload-type parts get
        // muted colors from the theme-safe midrange.
        const TYPE_STYLE: Partial<Record<string, { stroke: string; tag: string }>> = {
          parachute: { stroke: '#b06a35', tag: 'chute' },
          streamer: { stroke: '#a08c2e', tag: 'strmr' },
          shockcord: { stroke: '#8f7a8d', tag: 'cord' },
          masscomponent: { stroke: '#a85f5c', tag: 'mass' },
          centeringring: { stroke: '#6f8a5c', tag: 'CR' },
          bulkhead: { stroke: '#66748c', tag: 'BH' },
          engineblock: { stroke: '#7d7050', tag: 'EB' },
        };
        const style = TYPE_STYLE[child.type];
        const len = num(child, 'length', num(child, 'packedLength', 0.025));
        const r = Math.min(
          pRadius * 0.85,
          num(child, 'outerRadius', num(child, 'radius', num(child, 'packedRadius', pRadius * 0.7))),
        );
        const start = axialStart(child, len, pStart, pLen);
        const offsets = child.type === 'innertube'
          ? clusterOffsets(
            child['cluster'] as string | undefined,
            num(child, 'outerRadius', 0.0095),
            num(child, 'clusterScale', 1),
            num(child, 'clusterRotation', 0) + roll,
          )
          : [{ y: 0, z: 0 }];
        // Loaded motor: a brownish silhouette at the REAL case size, seated
        // flush against the mount's aft end (how motors actually load).
        const motor = child.type === 'innertube' && child.id ? motors?.[child.id] : undefined;
        for (const off of offsets) {
          // −y: the cross-section frame's +y is UP, and SVG y grows down.
          const oy = baseY - off.y * ctx.scale;
          const inkColor = isSel(child) ? 'var(--accent)' : fillOf(child, style?.stroke ?? '#9a978f');
          noteHover(child, ctx.x0 + start * ctx.scale, oy - r * ctx.scale,
            ctx.x0 + (start + len) * ctx.scale, oy + r * ctx.scale);
          overlay.push(
            <rect key={key++} x={ctx.x0 + start * ctx.scale}
              y={oy - r * ctx.scale}
              width={Math.max(2, len * ctx.scale)} height={2 * r * ctx.scale}
              fill={child.type === 'bulkhead' ? 'url(#bulkhead-hatch)' : 'rgba(127,127,127,0.001)'}
              stroke={inkColor} strokeWidth={selWidth(child)}
              strokeDasharray="3 2" {...grab}>
              <title>{child.name ?? DISPLAY_NAME[child.type]}</title>
            </rect>,
          );
          // Miniature glyphs (the owner's pick, 2026-08-05b #21): a picture inside
          // the box for chutes, mass items, centering rings and shock cords,
          // drawn whenever there's room; the text tag stays for the rest.
          const bw = len * ctx.scale;
          const bh = 2 * r * ctx.scale;
          const gcx = ctx.x0 + (start + len / 2) * ctx.scale;
          const gcy = oy;
          const gs = Math.min(bw * 0.8, bh * 0.7); // glyph box size
          if (gs >= 8) {
            const g = gs / 2;
            const glyphProps = { stroke: fillOf(child, style?.stroke ?? '#9a978f'), fill: 'none', strokeWidth: 1.2, style: { pointerEvents: 'none' as const } };
            if (child.type === 'parachute') {
              overlay.push(
                <g key={key++} {...glyphProps}>
                  <path d={`M ${gcx - g} ${gcy} A ${g} ${g} 0 0 1 ${gcx + g} ${gcy}`} />
                  <path d={`M ${gcx - g} ${gcy} L ${gcx} ${gcy + g} L ${gcx + g} ${gcy} M ${gcx - g * 0.45} ${gcy - g * 0.65} L ${gcx} ${gcy + g} M ${gcx + g * 0.45} ${gcy - g * 0.65} L ${gcx} ${gcy + g}`} />
                </g>,
              );
            } else if (child.type === 'masscomponent') {
              overlay.push(
                <g key={key++} {...glyphProps}>
                  <rect x={gcx - g * 0.7} y={gcy - g * 0.35} width={g * 1.4} height={g * 1.05}
                    fill={fillOf(child, style?.stroke ?? '#9a978f')} fillOpacity="0.35" />
                  <path d={`M ${gcx - g * 0.35} ${gcy - g * 0.35} A ${g * 0.4} ${g * 0.5} 0 0 1 ${gcx + g * 0.35} ${gcy - g * 0.35}`} />
                </g>,
              );
            } else if (child.type === 'centeringring') {
              // Ring cross-section: material near the walls, bore in the middle.
              overlay.push(
                <g key={key++} {...glyphProps}>
                  <line x1={gcx} y1={gcy - bh / 2 + 1.5} x2={gcx} y2={gcy - bh * 0.16} strokeWidth={Math.max(2, bw * 0.5)} />
                  <line x1={gcx} y1={gcy + bh * 0.16} x2={gcx} y2={gcy + bh / 2 - 1.5} strokeWidth={Math.max(2, bw * 0.5)} />
                </g>,
              );
            } else if (child.type === 'shockcord') {
              const seg = gs / 4;
              overlay.push(
                <path key={key++} {...glyphProps}
                  d={`M ${gcx - g} ${gcy} ${[1, 2, 3, 4].map((i) => `L ${gcx - g + i * seg * 2 - seg} ${gcy + (i % 2 ? -1 : 1) * g * 0.45} L ${gcx - g + i * seg * 2} ${gcy}`).join(' ')}`} />,
              );
            }
          }
          // Type tag, when the box has room for it — glyph types skip the
          // text once their picture is drawn. Counter-rotated tags read
          // horizontally in vertical mode, so the room roles swap.
          const hasGlyph = gs >= 8
            && ['parachute', 'masscomponent', 'centeringring', 'shockcord'].includes(child.type);
          const tagRoom = vertical
            ? 2 * r * ctx.scale > 26 && len * ctx.scale > 11
            : len * ctx.scale > 26 && 2 * r * ctx.scale > 11;
          if (style && !hasGlyph && tagRoom) {
            const tx = ctx.x0 + (start + len / 2) * ctx.scale;
            const ty = oy;
            overlay.push(
              <text key={key++} x={tx} y={ty}
                textAnchor="middle" dominantBaseline="central"
                fontSize="8.5" fill={fillOf(child, style.stroke)} {...textUp(tx, ty)}
                style={{ pointerEvents: 'none', textTransform: 'uppercase', letterSpacing: '0.04em' }}>
                {style.tag}
              </text>,
            );
          }
          if (motor) {
            overlay.push(...motorShapes(
              motor, start + len - motor.length + num(child, 'motorOverhang', 0),
              oy));
          }
        }
        renderChildren(child, start, len, r, baseY);
      }
    }
  };

  // Dashed outline for a shoulder sliding inside the adjacent tube. Painted in
  // the overlay pass — an aft shoulder lives inside the NEXT tube, which is
  // drawn later and would otherwise cover it.
  const shoulderRect = (startX: number, lenSi: number, rSi: number, color: string, baseY: number) => {
    if (lenSi <= 0 || rSi <= 0) return;
    overlay.push(
      <rect key={key++} x={ctx.x0 + startX * scale} y={baseY - rSi * scale}
        width={Math.max(1.5, lenSi * scale)} height={2 * rSi * scale}
        fill="rgba(127,127,127,0.001)" stroke={color} strokeWidth="1"
        strokeDasharray="3 2" style={{ pointerEvents: 'none' }} />,
    );
  };

  // Draws an axial nose→tail chain with its centerline at screen `baseY`
  // (ctx.cy for the core rocket; offset for each off-axis pod instance).
  const renderChain = (nodes: ComponentNode[], xStart: number, baseY: number) => {
    let cx = xStart;
    for (const n of nodes) {
      const len = num(n, 'length', 0);
      if (n.type === 'nosecone') {
        const r = num(n, 'aftRadius', 0.012);
        noteHover(n, ctx.x0 + cx * scale, baseY - r * scale, ctx.x0 + (cx + len) * scale, baseY + r * scale);
        shapes.push(<path key={key++} d={profilePath(ctx, n, cx, len, 0, r, baseY)} fill={fillOf(n, '#d5d2cb')}
          stroke={selStroke(n, '#7a786f')} strokeWidth={selWidth(n)} {...clickable(n)} />);
        shoulderRect(cx + len, num(n, 'shoulderLength', 0), num(n, 'shoulderRadius', 0), '#9a978f', baseY);
        renderChildren(n, cx, len, r, baseY);
        cx += len;
      } else if (n.type === 'bodytube') {
        const r = num(n, 'outerRadius', 0.012);
        noteHover(n, ctx.x0 + cx * scale, baseY - r * scale, ctx.x0 + (cx + len) * scale, baseY + r * scale);
        shapes.push(
          <rect key={key++} x={ctx.x0 + cx * scale} y={baseY - r * scale}
            width={len * scale} height={2 * r * scale}
            fill={fillOf(n, '#e7e5e0')} stroke={selStroke(n, '#7a786f')}
            strokeWidth={selWidth(n)} {...clickable(n)} />,
        );
        // Min-diameter: a motor loaded directly in this body tube draws at its
        // real case size, seated flush against the tube's aft end.
        const tubeMotor = n.id ? motors?.[n.id] : undefined;
        if (tubeMotor) {
          shapes.push(...motorShapes(
            tubeMotor, cx + len - tubeMotor.length + num(n, 'motorOverhang', 0), baseY));
        }
        renderChildren(n, cx, len, r, baseY);
        cx += len;
      } else if (n.type === 'transition') {
        const rf = num(n, 'foreRadius', 0.012);
        const ra = num(n, 'aftRadius', 0.009);
        noteHover(n, ctx.x0 + cx * scale, baseY - Math.max(rf, ra) * scale,
          ctx.x0 + (cx + len) * scale, baseY + Math.max(rf, ra) * scale);
        shapes.push(
          <path key={key++} d={profilePath(ctx, n, cx, len, rf, ra, baseY)}
            fill={fillOf(n, '#d5d2cb')} stroke={selStroke(n, '#7a786f')}
            strokeWidth={selWidth(n)} {...clickable(n)} />,
        );
        const fsl = num(n, 'foreShoulderLength', 0);
        shoulderRect(cx - fsl, fsl, num(n, 'foreShoulderRadius', 0), '#9a978f', baseY);
        shoulderRect(cx + len, num(n, 'aftShoulderLength', 0), num(n, 'aftShoulderRadius', 0), '#9a978f', baseY);
        renderChildren(n, cx, len, Math.max(rf, ra), baseY);
        cx += len;
      }
    }
  };

  renderChain(chain, 0, ctx.cy);

  const cgX = info ? ctx.x0 + info.cg * scale : null;
  const cpX = info ? ctx.x0 + info.cp * scale : null;
  const stab = info ? stabilityState(info.stabilityCalibers) : null;
  const marginText = info && stab
    ? `${STABILITY_GLYPH[stab]} ${formatStability(info, prefs.stabilityUnit)} — ${STABILITY_WORD[stab]}`
    : null;
  const callouts = calloutLayout(cgX, cpX, ctx.cy, vHalf * scale, w, h, marginText, gutY, gutX);

  /**
   * The ruler gutters: a horizontal scale along the top reading axial
   * distance from the nose tip, and a vertical one down the left reading
   * distance from the centreline, both in the Preferences length unit. The
   * tick ladder is the desktop's own (services/rulerTicks).
   *
   * `view` is a zoom/pan state, not necessarily the live one — the export
   * needs the same rulers drawn for the identity view, since it always shows
   * the whole rocket whatever the screen is zoomed to.
   */
  const lenUnit = prefs.units.length;
  const pxPerUnit = scale * uiToSi('length', lenUnit, 1);
  const rulerGutters = (view: { k: number; x: number; y: number }, forExport: boolean) => {
    const across = rulerLayout(view.x + view.k * ctx.x0, view.k * pxPerUnit, gutX, w, RULER_TOP);
    const down = rulerLayout(view.y + view.k * ctx.cy, -view.k * pxPerUnit, gutY, h, RULER_LEFT);
    const band = 'var(--surface-2)';
    const edge = 'var(--border)';
    const ink = 'var(--text-secondary)';
    return (
      <g key={forExport ? 'ruler-fit' : 'ruler-view'}
        data-ruler={forExport ? 'fit' : 'view'} display={forExport ? 'none' : undefined}
        pointerEvents="none" fontSize="9" fill={ink}>
        <rect x={rollW} y={0} width={w - rollW} height={RULER_TOP} fill={band} />
        <rect x={rollW} y={0} width={RULER_LEFT} height={h} fill={band} />
        <path d={`M ${rollW} ${RULER_TOP} H ${w} M ${gutX} 0 V ${h}`} stroke={edge} strokeWidth="1" fill="none" />
        {across.map((t, i) => (
          <g key={`h${i}`}>
            <line x1={t.px} y1={RULER_TOP - t.len} x2={t.px} y2={RULER_TOP} stroke={ink} strokeWidth="1" />
            {t.label !== null && (
              <text x={t.px + 1.5} y={RULER_TOP - t.len - 2} fontWeight={t.bold ? 700 : 400}>{t.label}</text>
            )}
          </g>
        ))}
        {down.map((t, i) => (
          <g key={`v${i}`}>
            <line x1={gutX - t.len} y1={t.px} x2={gutX} y2={t.px} stroke={ink} strokeWidth="1" />
            {t.label !== null && (
              <text x={rollW + 1.5} y={t.px - 2} fontWeight={t.bold ? 700 : 400}>{t.label}</text>
            )}
          </g>
        ))}
        {/* The desktop parks a unit selector in this corner; ours only reports
            the unit, because it is the Preferences length unit and changing it
            here would silently change it everywhere else. */}
        <rect x={rollW} y={0} width={RULER_LEFT} height={RULER_TOP} fill={band} />
        <path d={`M ${gutX} 0 V ${RULER_TOP} H ${rollW}`} stroke={edge} strokeWidth="1" fill="none" />
        <text x={rollW + RULER_LEFT / 2} y={RULER_TOP / 2} textAnchor="middle" dominantBaseline="central"
          fontWeight={600}>{lenUnit}</text>
      </g>
    );
  };
  const viewIsFit = zoom.k === 1 && zoom.x === 0 && zoom.y === 0;

  // Hover overlay (S5): a light accent wash over the hovered component's
  // extent plus a name tag — deliberately fainter than the solid width-2
  // selection outline so the two stay distinguishable.
  const hoverBox = hoverBoxes.length
    ? hoverBoxes.reduce((a, b) => ({
      x0: Math.min(a.x0, b.x0), y0: Math.min(a.y0, b.y0),
      x1: Math.max(a.x1, b.x1), y1: Math.max(a.y1, b.y1),
    }))
    : null;
  let hoverTag: { x: number; y: number; tw: number } | null = null;
  if (hoverBox) {
    const tw = hoverName.length * 6.2 + 14;
    hoverTag = {
      x: Math.min(w - tw / 2 - 2, Math.max(gutX + tw / 2 + 2, (hoverBox.x0 + hoverBox.x1) / 2)),
      // Above the component unless that leaves the drawing area (the ruler
      // gutter is not drawing area); then below.
      y: hoverBox.y0 - 22 >= gutY + 2 ? hoverBox.y0 - 13 : Math.min(h - 11, hoverBox.y1 + 13),
      tw,
    };
  }

  return (
    <div ref={wrapRef} style={{ position: 'relative', ...(vertical || fillHeight ? { height: '100%' } : null) }}>
      <svg ref={svgRef} viewBox={vertical ? `0 0 ${h} ${w}` : `0 0 ${w} ${h}`}
          style={vertical
            ? { height: '100%', maxWidth: '100%', display: 'block', margin: '0 auto' }
            : { width: '100%', height: 'auto', display: 'block', touchAction: 'none',
              cursor: zoom.k > 1 ? 'grab' : undefined }}
          role="img"
          aria-label={vertical
            ? 'Rocket side view, nose up, with CG and CP markers'
            : 'Rocket side view with CG and CP markers — drag components, wheel to zoom, drag background to pan'}
          onPointerDownCapture={resetDragLatch}
          onPointerDown={vertical ? undefined : beginPan}
          onPointerMove={vertical ? undefined : onMove}
          onPointerUp={vertical ? undefined : endDrag}
          onPointerLeave={vertical ? undefined : endDrag}>
        <defs>
          {/* Bulkhead fill: the engineering-drawing diagonal hatch. */}
          <pattern id="bulkhead-hatch" patternUnits="userSpaceOnUse" width="5" height="5">
            <path d="M0 5 L5 0" stroke="#66748c" strokeWidth="0.9" />
          </pattern>
        </defs>
        {/* Vertical: one rigid rotation of the horizontal layout — the w×h
            layout rect maps exactly onto the transposed h×w viewBox with the
            nose (layout left) up. rotate(-90) would put it nose DOWN. */}
        <g transform={vertical
          ? `rotate(90 ${h / 2} ${h / 2})`
          : `translate(${zoom.x} ${zoom.y}) scale(${zoom.k})`}>
          {shapes}
          {overlay}
          {/* pointerEvents none on BOTH marker groups: they are decoration
              drawn on the centreline — precisely where you click to select a
              nose cone or body tube — and an 18px opaque disc with no handler
              of its own silently ate the click. Same rule the callout group
              below already follows. */}
          {cgX !== null && (
            <g pointerEvents="none">
              <circle cx={cgX} cy={ctx.cy} r={MARKER_R} fill="var(--surface-1)" stroke="var(--text-primary)" strokeWidth="1.5" />
              <path d={`M ${cgX} ${ctx.cy} L ${cgX + MARKER_R} ${ctx.cy} A ${MARKER_R} ${MARKER_R} 0 0 1 ${cgX} ${ctx.cy + MARKER_R} Z`} fill="var(--text-primary)" />
              <path d={`M ${cgX} ${ctx.cy} L ${cgX - MARKER_R} ${ctx.cy} A ${MARKER_R} ${MARKER_R} 0 0 1 ${cgX} ${ctx.cy - MARKER_R} Z`} fill="var(--text-primary)" />
            </g>
          )}
          {cpX !== null && (
            <g pointerEvents="none">
              <circle cx={cpX} cy={ctx.cy} r={MARKER_R} fill="none" stroke="var(--status-serious)" strokeWidth="2" />
              <circle cx={cpX} cy={ctx.cy} r={3.5} fill="var(--status-serious)" />
            </g>
          )}
          {(callouts.cg || callouts.cp) && (
            <g pointerEvents="none">
              {callouts.cg && (
                <>
                  <line x1={callouts.cg.x} y1={callouts.cg.leaderY1} x2={callouts.cg.x} y2={callouts.cg.leaderY2}
                    stroke="var(--text-primary)" strokeWidth="1" strokeDasharray="4 3" />
                  <circle cx={callouts.cg.x} cy={callouts.cg.leaderY2} r={4} fill="var(--text-primary)" />
                  <text x={callouts.cg.x + 8} y={callouts.cg.leaderY2} dominantBaseline="central"
                    fontSize="11" fontWeight="bold" fill="var(--text-primary)"
                    {...textUp(callouts.cg.x + 8, callouts.cg.leaderY2)}>CG</text>
                </>
              )}
              {callouts.cp && (
                <>
                  <line x1={callouts.cp.x} y1={callouts.cp.leaderY1} x2={callouts.cp.x} y2={callouts.cp.leaderY2}
                    stroke="var(--status-serious)" strokeWidth="1" strokeDasharray="4 3" />
                  <circle cx={callouts.cp.x} cy={callouts.cp.leaderY2} r={4} fill="var(--status-serious)" />
                  <text x={callouts.cp.x + 8} y={callouts.cp.leaderY2} dominantBaseline="central"
                    fontSize="11" fontWeight="bold" fill="var(--status-serious)"
                    {...textUp(callouts.cp.x + 8, callouts.cp.leaderY2)}>CP</text>
                </>
              )}
              {callouts.margin && stab && (
                <text x={callouts.margin.x} y={callouts.margin.y} textAnchor="middle" dominantBaseline="central"
                  fontSize="13" fontWeight="bold" fill={STABILITY_VAR[stab]}
                  {...textUp(callouts.margin.x, callouts.margin.y)}>{marginText}</text>
              )}
            </g>
          )}
          {hoverBox && hoverTag && (
            <g pointerEvents="none">
              <rect x={hoverBox.x0 - 2} y={hoverBox.y0 - 2}
                width={hoverBox.x1 - hoverBox.x0 + 4} height={hoverBox.y1 - hoverBox.y0 + 4}
                rx="3" fill="var(--accent)" fillOpacity="0.14"
                stroke="var(--accent)" strokeWidth="1" strokeOpacity="0.6" />
              <g {...textUp(hoverTag.x, hoverTag.y)}>
                <rect x={hoverTag.x - hoverTag.tw / 2} y={hoverTag.y - 9}
                  width={hoverTag.tw} height={18} rx="4"
                  fill="rgba(13,14,18,0.9)" stroke="var(--border)" strokeWidth="1" />
                <text x={hoverTag.x} y={hoverTag.y} textAnchor="middle" dominantBaseline="central"
                  fontSize="11" fill="#ffffff">{hoverName}</text>
              </g>
            </g>
          )}
        </g>
        {/* Rulers ride OUTSIDE the zoom group — the gutters stay pinned to the
            canvas edge while the ticks track pan and zoom. That is also why
            the export needs a second copy: schematicSvg resets the view group
            to identity, which it cannot do to tick positions already baked in
            px, so a fit-view copy travels along hidden and is swapped in. */}
        {rulers && rulerGutters(zoom, false)}
        {rulers && !viewIsFit && rulerGutters({ k: 1, x: 0, y: 0 }, true)}
      </svg>
      {/* Read-mostly ⟳90° mode has no controls at all. */}
      {!vertical && <RollControl roll={roll} onRoll={setRoll} top={gutY} />}
      {/* Vertical is read-mostly: no zoom to fit-reset, and the SVG/image
          exports assume the horizontal drawing (identity view transform), so
          the whole strip hides rather than export a sideways page. */}
      {!vertical && <div className="schematic-controls" style={gutY ? { top: gutY + 6 } : undefined}>
        {exportData && (
          <>
            <button className="file-btn"
              title="True-scale 2D drawing (SVG) with design data — physical mm size, prints at 100% scale"
              onClick={() => {
                if (!svgRef.current) return;
                try {
                  const data = { ...exportData, spanM: 2 * vHalf };
                  downloadBlob(schematicSvg(svgRef.current, scale, w, h, data),
                    `${data.name.replace(/[^\w-]+/g, '_')}-2d.svg`);
                } catch (e) {
                  onError?.(`SVG export failed: ${e instanceof Error ? e.message : String(e)}`);
                }
              }}>
              ⬇ SVG
            </button>
            <ImageExportMenu label="⬇ Image"
              title="High-resolution 2D image with design data — pick PNG or JPG and a width"
              onPick={async (format, widthPx) => {
                if (!svgRef.current) return;
                try {
                  const data = { ...exportData, spanM: 2 * vHalf };
                  const svg = schematicSvg(svgRef.current, scale, w, h, data);
                  downloadBlob(await svgToImage(svg, widthPx, format),
                    `${data.name.replace(/[^\w-]+/g, '_')}-2d.${IMAGE_FORMAT_EXT[format]}`);
                } catch (e) {
                  onError?.(`Image export failed: ${e instanceof Error ? e.message : String(e)}`
                    + ' — try a smaller width, or use ⬇ SVG.');
                }
              }} />
          </>
        )}
        <button className="file-btn"
          title={rulers ? 'Hide the dimensional rulers' : 'Show dimensional rulers along the top and left'}
          aria-label={rulers ? 'Hide rulers' : 'Show rulers'} aria-pressed={rulers}
          onClick={() => setPrefs({ ...prefs, rulers2d: !rulersPref })}>📏</button>
        {(zoom.k > 1 || zoom.x !== 0 || zoom.y !== 0) && (
          <button className="file-btn"
            title="Fit the whole rocket in view"
            onClick={() => setZoom({ k: 1, x: 0, y: 0 })}>
            ⤢ Fit
          </button>
        )}
        <button className="file-btn" title="Zoom in — or scroll on the drawing; drag to pan"
          aria-label="Zoom in" onClick={() => zoomBy(1.5)} disabled={zoom.k >= 12}>+</button>
        <button className="file-btn" title="Zoom out"
          aria-label="Zoom out" onClick={() => zoomBy(1 / 1.5)} disabled={zoom.k <= 1}>−</button>
      </div>}
    </div>
  );
}

function collect<T>(nodes: ComponentNode[], f: (n: ComponentNode) => T): T[] {
  const out: T[] = [];
  const walk = (ns: ComponentNode[]) => {
    for (const n of ns) {
      out.push(f(n));
      walk(n.children ?? []);
    }
  };
  walk(nodes);
  return out;
}

/**
 * Closed side-view outline of a nose cone (foreR = 0) or transition, sampled
 * from the kernel-exact profile: top edge fore→aft, aft edge down, bottom
 * edge aft→fore, Z closes the fore edge.
 */
function profilePath(
  ctx: Ctx, n: ComponentNode, x: number, len: number,
  foreR: number, aftR: number, baseY: number,
): string {
  const shape = typeof n['shape'] === 'string' ? (n['shape'] as string)
    : n.type === 'transition' ? 'conical' : 'ogive';
  const param = typeof n['shapeParameter'] === 'number' ? (n['shapeParameter'] as number) : undefined;
  // node['clipped'] (.ork <shapeclipped>) rides along so an unclipped
  // transition draws the way it simulates; absent = kernel default (clipped).
  const pts = outerProfile(shape, param, len, foreR, aftR, 24, undefined,
    typeof n['clipped'] === 'boolean' ? (n['clipped'] as boolean) : undefined);
  const px = (xi: number) => ctx.x0 + (x + xi) * ctx.scale;
  const top = pts.map(([xi, r]) => `${px(xi)} ${baseY - r * ctx.scale}`);
  const bottom = pts.slice().reverse().map(([xi, r]) => `${px(xi)} ${baseY + r * ctx.scale}`);
  return `M ${top.join(' L ')} L ${bottom.join(' L ')} Z`;
}
